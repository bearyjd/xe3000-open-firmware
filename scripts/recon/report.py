"""Generate docs/findings/*.md tables from findings/raw/<run-id>/. Every row links its evidence.

Excerpts are not copied into reports (nothing proprietary lands in the repo): rows carry file:line and
the engine-computed excerpt hash instead.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

from recon import canary

EVIDENCE_BASE = "harvest"  # evidence files live in the gitignored zones; links are local
UNGROUNDED_LABEL = "UNGROUNDED"
GROUNDED_LABEL = "grounded"
HASH_SHOWN = 12
GENERATED_NOTE = "<!-- generated by scripts/recon/report.py; do not edit by hand -->"


MAX_CLAIM_CHARS = 300


def _cell(text: str) -> str:
    """Plain table-cell text: single line, pipes escaped."""
    return " ".join(str(text).split()).replace("|", "\\|")


def _code(text: str, limit: int = MAX_CLAIM_CHARS) -> str:
    """Model-supplied text as an inline code span: no markdown, HTML or link syntax can take effect."""
    flat = " ".join(str(text).split())[:limit].replace("`", "'")
    flat = flat.replace("<", "&lt;").replace(">", "&gt;")
    return "`" + flat.replace("|", "\\|") + "`"


def _evidence_link(ev: dict) -> str:
    zone, _, rest = ev["file"].partition("/")
    target = f"{EVIDENCE_BASE}/redacted/{rest}" if zone == "redacted" else ev["file"]
    label = _code(f"{ev['file']}:{ev['line']}", limit=200)
    return f"[{label}](<{quote(target, safe='/')}#L{int(ev['line'])}>) `{ev['excerpt_sha256'][:HASH_SHOWN]}`"


def _row(f: dict) -> str:
    status = UNGROUNDED_LABEL if f["ungrounded"] else GROUNDED_LABEL
    note = f" {_code('; '.join(f['ungrounded']))}" if f["ungrounded"] else ""
    links = "<br>".join(_evidence_link(e) for e in f["evidence"])
    return f"| {_code(f['claim'])} | {_cell(f['confidence'])} | {status}{note} | {links} |"


def render_category(category: str, findings: list[dict], run_id: str) -> str:
    head = [GENERATED_NOTE, f"# Findings: {category}", "", f"Run: `{run_id}`. Findings flagged "
            f"{UNGROUNDED_LABEL} name items absent from the deterministic ground truth.", "",
            "| Claim | Confidence | Status | Evidence |", "|---|---|---|---|"]
    return "\n".join([*head, *(_row(f) for f in findings)]) + "\n"


def render_index(counts: dict[str, int], run_id: str) -> str:
    rows = [f"| [{c}]({c}.md) | {n} |" for c, n in sorted(counts.items())]
    return "\n".join([GENERATED_NOTE, "# Findings index", "", f"Run: `{run_id}`", "",
                      "| Category | Findings |", "|---|---|", *rows]) + "\n"


def load_findings(run_dir: Path, sanitizer: canary.Sanitizer | None = None) -> list[dict]:
    """Findings with any known secret (canary file) removed, whatever the model echoed."""
    san = sanitizer or canary.Sanitizer.from_file()
    path = Path(run_dir) / "findings.jsonl"
    return [san.obj(json.loads(line)) for line in path.read_text().splitlines() if line.strip()]


def generate(run_dir: Path, out_dir: Path, sanitizer: canary.Sanitizer | None = None) -> list[Path]:
    """Write one markdown file per category plus index.md; return the written paths."""
    run_dir, out_dir = Path(run_dir), Path(out_dir)
    by_category: dict[str, list[dict]] = defaultdict(list)
    for f in load_findings(run_dir, sanitizer):
        by_category[f["category"]].append(f)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for category, findings in sorted(by_category.items()):
        path = out_dir / f"{category}.md"
        path.write_text(render_category(category, findings, run_dir.name))
        written.append(path)
    index = out_dir / "index.md"
    index.write_text(render_index({c: len(v) for c, v in by_category.items()}, run_dir.name))
    return [*written, index]


def main(argv: list[str] | None = None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description="Generate docs/findings/*.md from a findings run.")
    ap.add_argument("--run-dir", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=Path("docs/findings"))
    args = ap.parse_args(argv)
    for path in generate(args.run_dir, args.out):
        print(f"wrote {path}")
    return 0
